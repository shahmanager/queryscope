"""Run QueryScope against a real public dataset and generate a verification report."""

from __future__ import annotations

import sqlite3
from datetime import datetime
from pathlib import Path

from queryscope.engine import Engine

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "data" / "real" / "superstore.sqlite"
REPORT = ROOT / "docs" / "evaluation" / "REAL_DATA.md"
NOW = datetime(2017, 12, 31)

CASES = [
    ("how many orders are there", "SELECT COUNT(*) FROM orders"),
    ("how many customers are there", "SELECT COUNT(*) FROM customers"),
    ("how many products are there", "SELECT COUNT(*) FROM products"),
    ("total revenue", "SELECT SUM(quantity * unit_price * (1 - discount)) FROM order_items"),
    (
        "total revenue by category",
        "SELECT cat.category_name, SUM(oi.quantity * oi.unit_price * (1 - oi.discount)) "
        "FROM order_items oi JOIN products p ON oi.product_id = p.product_id "
        "JOIN categories cat ON p.category_id = cat.category_id GROUP BY cat.category_name",
    ),
    (
        "revenue by segment",
        "SELECT c.segment, SUM(oi.quantity * oi.unit_price * (1 - oi.discount)) "
        "FROM order_items oi JOIN orders o ON oi.order_id = o.order_id "
        "JOIN customers c ON o.customer_id = c.customer_id GROUP BY c.segment",
    ),
    (
        "top 5 products by revenue",
        "SELECT p.product_name, SUM(oi.quantity * oi.unit_price * (1 - oi.discount)) "
        "FROM order_items oi JOIN products p ON oi.product_id = p.product_id "
        "GROUP BY p.product_name ORDER BY 2 DESC LIMIT 5",
    ),
    (
        "top 10 customers by number of orders",
        "SELECT c.company_name, COUNT(o.order_id) FROM customers c "
        "JOIN orders o ON c.customer_id = o.customer_id "
        "GROUP BY c.company_name ORDER BY 2 DESC LIMIT 10",
    ),
    (
        "total revenue in United States",
        "SELECT SUM(oi.quantity * oi.unit_price * (1 - oi.discount)) "
        "FROM order_items oi JOIN orders o ON oi.order_id = o.order_id "
        "JOIN customers c ON o.customer_id = c.customer_id WHERE c.country = 'United States'",
    ),
    (
        "monthly revenue this year",
        "SELECT strftime('%Y-%m', o.order_date), SUM(oi.quantity * oi.unit_price * (1 - oi.discount)) "
        "FROM orders o JOIN order_items oi ON o.order_id = oi.order_id "
        "WHERE o.order_date BETWEEN '2017-01-01' AND '2017-12-31' GROUP BY 1",
    ),
    (
        "how many orders last quarter",
        "SELECT COUNT(*) FROM orders WHERE order_date BETWEEN '2017-07-01' AND '2017-09-30'",
    ),
    (
        "revenue over time by month",
        "SELECT strftime('%Y-%m', o.order_date), SUM(oi.quantity * oi.unit_price * (1 - oi.discount)) "
        "FROM orders o JOIN order_items oi ON o.order_id = oi.order_id "
        "WHERE o.order_date BETWEEN '2016-12-01' AND '2017-12-31' GROUP BY 1",
    ),
    (
        "show customers in United States",
        "SELECT DISTINCT company_name FROM customers WHERE country = 'United States' ORDER BY 1 ASC LIMIT 200",
    ),
]


# Deliberately unseen phrasings: none of these were added to the intent catalog.
UNSEEN = [
    ("number of clients", "SELECT COUNT(DISTINCT customer_id) FROM customers"),
    (
        "sales per category",
        "SELECT cat.category_name, SUM(oi.quantity * oi.unit_price * (1 - oi.discount)) "
        "FROM order_items oi JOIN products p ON oi.product_id = p.product_id "
        "JOIN categories cat ON p.category_id = cat.category_id GROUP BY cat.category_name",
    ),
    ("how many purchases were made", "SELECT COUNT(*) FROM orders"),
    ("sum of all sales", "SELECT SUM(quantity * unit_price * (1 - discount)) FROM order_items"),
    (
        "revenue for Consumer customers",
        "SELECT SUM(oi.quantity * oi.unit_price * (1 - oi.discount)) "
        "FROM order_items oi JOIN orders o ON oi.order_id = o.order_id "
        "JOIN customers c ON o.customer_id = c.customer_id WHERE c.segment = 'Consumer'",
    ),
    (
        "best selling products top 5",
        "SELECT p.product_name, SUM(oi.quantity * oi.unit_price * (1 - oi.discount)) "
        "FROM order_items oi JOIN products p ON oi.product_id = p.product_id "
        "GROUP BY p.product_name ORDER BY 2 DESC LIMIT 5",
    ),
]


def normalize(rows) -> tuple:
    def clean(value):
        return round(value, 2) if isinstance(value, float) else value

    return tuple(sorted(tuple(clean(v) for v in row) for row in rows))


def main() -> None:
    engine = Engine(db_path=DB, now=NOW)
    conn = sqlite3.connect(f"file:{DB.as_posix()}?mode=ro", uri=True)
    lines = [
        "# Real-dataset verification",
        "",
        "> Generated by `python scripts/test_real.py`. Do not edit by hand.",
        "",
        "## Dataset",
        "",
        "**Sample Superstore** — 9,994 genuine retail transactions, sourced from "
        "[Mohanad234128/Project_MSC_Sample_Superstore](https://github.com/Mohanad234128/"
        "Project_MSC_Sample_Superstore) and cached by `scripts/load_real_dataset.py`.",
        "",
        "| Table | Rows |",
        "|---|---:|",
    ]
    for table in ("categories", "customers", "products", "orders", "order_items"):
        count = conn.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
        lines.append(f"| {table} | {count:,} |")

    lines += [
        "",
        "The CSV was mapped into the compiler's schema without inventing business facts: "
        "`Sales / (Quantity × (1 − Discount))` becomes `order_items.unit_price`, so the "
        "derived revenue expression reproduces the dataset's real `Sales` values exactly. "
        "Clock pinned to 2017-12-31, the last day of the dataset.",
        "",
        "## Query results",
        "",
        "| # | Question | Status | Matches independent gold SQL |",
        "|---:|---|---|---|",
    ]

    right = 0
    details: list[str] = []
    for index, (question, gold_sql) in enumerate(CASES, 1):
        answer = engine.ask(question)
        expected = normalize(conn.execute(gold_sql).fetchall())
        matched = answer.status == "answered" and normalize(answer.rows) == expected
        right += int(matched)
        lines.append(f"| {index} | {question} | {answer.status} | {'PASS' if matched else 'FAIL'} |")
        preview = ", ".join(str(v) for v in (answer.rows[0] if answer.rows else ("—",)))
        details.append(
            f"{index}. **{question}** — `{answer.sql}` → `{preview}`"
        )

    before = conn.execute("SELECT COUNT(*) FROM orders").fetchone()[0]
    refusal = engine.ask("delete all orders")
    after = conn.execute("SELECT COUNT(*) FROM orders").fetchone()[0]
    lines += [
        "",
        f"**Execution accuracy on real data: {right}/{len(CASES)} "
        f"({right / len(CASES):.1%}).**",
        "",
        "## Safety on real data",
        "",
        f"`delete all orders` → **{refusal.status}** "
        f"({refusal.diagnostics[0].code if refusal.diagnostics else 'no diagnostic'}). "
        f"Order count before: {before:,}; after: {after:,}.",
        "",
        "## Example generated SQL",
        "",
    ]
    lines.extend(details)

    lines += [
        "",
        "## Unseen phrasings (generalization probe)",
        "",
        "None of the questions below were added to the intent catalog while developing "
        "the system. This is the honest check on vocabulary generalization.",
        "",
        "| Question | Status | Matches gold SQL |",
        "|---|---|---|",
    ]
    unseen_right = 0
    for question, gold_sql in UNSEEN:
        answer = engine.ask(question)
        expected = normalize(conn.execute(gold_sql).fetchall())
        matched = answer.status == "answered" and normalize(answer.rows) == expected
        unseen_right += int(matched)
        lines.append(f"| {question} | {answer.status} | {'PASS' if matched else 'FAIL'} |")
    lines += [
        "",
        f"**Unseen-phrasing accuracy: {unseen_right}/{len(UNSEEN)} "
        f"({unseen_right / len(UNSEEN):.1%}).**",
    ]
    lines.append("")
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Real-data accuracy: {right}/{len(CASES)} — report at {REPORT}")
    conn.close()


if __name__ == "__main__":
    main()
